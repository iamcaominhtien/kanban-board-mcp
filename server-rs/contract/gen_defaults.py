"""Writes src/move_db/defaults.rs: the scalar defaults of the Python models' required columns, which the copy fills
in where a source row has no value (`dbkit/move.py`, `_copy_table`: `c.default.arg` where `c.default.is_scalar`).

Run from `server/` with the server's Python and folders of its own:

    KANBAN_CONFIG_DIR=$(mktemp -d) KANBAN_DB_PATH=$(mktemp -d)/kanban.db KANBAN_LOG_DIR=$(mktemp -d) \
      .venv/bin/python ../server-rs/contract/gen_defaults.py
"""

import json
import os
import sys

sys.path.insert(0, os.getcwd())

from sqlmodel import SQLModel  # noqa: E402

import models  # noqa: E402,F401 - registers every table

OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "crates", "kb-dbkit", "src", "move_db", "defaults.rs"
)


def literal(value) -> str:
    if isinstance(value, bool):
        return f"Default::Bool({'true' if value else 'false'})"
    if isinstance(value, int):
        return f"Default::Int({value})"
    if isinstance(value, float):
        return f"Default::Float({value!r})"
    if isinstance(value, str):
        return f"Default::Str({json.dumps(value, ensure_ascii=False)})"
    raise TypeError(f"no literal for {value!r}")


lines = [
    "//! The scalar defaults of the Python models' required columns. Generated by `contract/gen_defaults.py`; do not",
    "//! edit.",
    "",
    "/// A default as the Python model declares it.",
    "#[derive(Debug, Clone, Copy, PartialEq)]",
    "pub enum Default {",
    "    Bool(bool),",
    "    Int(i64),",
    "    Float(f64),",
    "    Str(&'static str),",
    "}",
    "",
    "/// (table, column, default) for every required column whose model default is a plain value, in the order of the",
    "/// metadata.",
    "pub const DEFAULTS: &[(&str, &str, Default)] = &[",
]
for table in SQLModel.metadata.sorted_tables:
    for c in table.columns:
        if not c.nullable and c.default is not None and getattr(c.default, "is_scalar", False):
            lines.append(f'    ("{table.name}", "{c.name}", {literal(c.default.arg)}),')
lines.append("];")
with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(f"{os.path.normpath(OUT)}: {len(lines) - 16} defaults")
