"""Write `crates/kb-doctext/src/pyuni_tables.rs`: the characters Python's `re` calls `\\w` and `\\d`.

Python 3.12 uses Unicode 15; the `regex` crate and `char` methods follow a newer Unicode, and `\\w` is not the same set
in the two engines anyway (Python: letters, numbers and `_`; Rust: also marks and connector punctuation). The docs
text modules need Python's sets, so they are generated from `re` itself.

Run from `server/`: `.venv/bin/python ../server-rs/contract/golden/gen_docs_text_tables.py`
"""

import os
import re
import sys
import unicodedata

OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..", "..", "crates", "kb-doctext", "src", "pyuni_tables.rs",
)


def ranges(pattern: str) -> list[tuple[int, int]]:
    rx = re.compile(pattern)
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(0x110000):
        hit = bool(rx.match(chr(cp)))
        if hit and start is None:
            start = cp
        if not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name: str, doc: str, rs: list[tuple[int, int]]) -> str:
    body = "".join(f"    (0x{a:X}, 0x{b:X}),\n" for a, b in rs)
    return f"/// {doc}\npub const {name}: &[(u32, u32)] = &[\n{body}];\n\n"


def main() -> None:
    text = (
        "//! Generated by `contract/golden/gen_docs_text_tables.py` from Python's `re` "
        f"(Unicode {unicodedata.unidata_version}). Do not edit.\n\n"
    )
    text += emit("WORD", "The characters `\\w` matches in a Python `str` pattern, as inclusive ranges.", ranges(r"\w"))
    text += emit("DECIMAL", "The characters `\\d` matches in a Python `str` pattern.", ranges(r"\d"))
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote", os.path.normpath(OUT), file=sys.stderr)


if __name__ == "__main__":
    main()
