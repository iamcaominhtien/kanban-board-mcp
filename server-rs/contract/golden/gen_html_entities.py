"""The tables behind Python's `html.unescape`, for crates/kb-draw (`diagram_model.plain` flattens HTML labels with it).

Run from `server/`:  .venv/bin/python ../server-rs/contract/golden/gen_html_entities.py
Writes `crates/kb-draw/src/html_entities.rs` (generated: do not edit).
"""

import html
import html.entities
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "crates" / "kb-draw" / "src" / "html_entities.rs"


def lit(text: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in text) + '"'


def main() -> None:
    named = sorted(html.entities.html5.items())
    invalid_refs = sorted(html._invalid_charrefs.items())
    invalid_points = sorted(html._invalid_codepoints)
    out = [
        "//! Generated by `contract/golden/gen_html_entities.py` from Python's `html` module: do not edit.",
        "",
        "/// `html.entities.html5`, sorted by name (names with and without the final `;`).",
        "pub static NAMED: &[(&str, &str)] = &[",
    ]
    for name, value in named:
        out.append(f'    ("{name}", {lit(value)}),')
    out += [
        "];",
        "",
        "/// `html._invalid_charrefs`: numeric references that are replaced by another character.",
        "pub static INVALID_CHARREFS: &[(u32, &str)] = &[",
    ]
    for num, value in invalid_refs:
        out.append(f"    ({num}, {lit(value)}),")
    out += [
        "];",
        "",
        "/// `html._invalid_codepoints`: numeric references that are dropped.",
        "pub static INVALID_CODEPOINTS: &[u32] = &[",
    ]
    for i in range(0, len(invalid_points), 12):
        out.append("    " + ", ".join(str(p) for p in invalid_points[i : i + 12]) + ",")
    out.append("];")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(named)} entities, {len(invalid_refs)} replaced, {len(invalid_points)} dropped -> {OUT}")


main()
