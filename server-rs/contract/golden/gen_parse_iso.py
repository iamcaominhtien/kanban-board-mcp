def of_fromisoformat(text: str):
    try:
        value = datetime.fromisoformat(text)
    except ValueError:
        return {"in": text, "ok": False}
    offset = value.utcoffset()
    out = {
        "in": text,
        "ok": True,
        "naive": offset is None,
        # the wall time as written, and the instant when the text has an offset
        "wall": value.replace(tzinfo=None).isoformat(),
        "offset": None if offset is None else offset.total_seconds(),
        "utc": None,
    }
    if offset is not None:
        try:
            out["utc"] = value.astimezone(timezone.utc).isoformat()
        except OverflowError:
            out["utc"] = "overflow"
    return out


ADAPTER = TypeAdapter(Optional[datetime])


def of_pydantic(text: str):
    try:
        value = ADAPTER.validate_python(text)
    except ValidationError as exc:
        return {"in": text, "ok": False, "type": exc.errors()[0]["type"]}
    offset = value.utcoffset()
    return {
        "in": text,
        "ok": True,
        "naive": offset is None,
        "wall": value.replace(tzinfo=None).isoformat(),
        "offset": None if offset is None else offset.total_seconds(),
    }


def main() -> None:
    out = {
        "python": ".".join(map(str, sys.version_info[:3])),
        "fromisoformat": [of_fromisoformat(s) for s in SHAPES],
        "query_datetime": [of_pydantic(s) for s in SHAPES + QUERY_ONLY],
    }
    OUT.write_text(json.dumps(out, indent=1, ensure_ascii=True) + "\n", encoding="utf-8")
    refused = sum(1 for c in out["fromisoformat"] if not c["ok"])
    print(f"{len(out['fromisoformat'])} fromisoformat cases ({refused} refused), {len(out['query_datetime'])} query cases")


if __name__ == "__main__":
    main()
