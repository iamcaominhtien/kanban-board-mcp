#!/usr/bin/env python3
"""Summarise the regression bug log and check the release rule.

Usage:
    python3 docs/regression-4.0.1/status.py           rewrite STATUS.md
    python3 docs/regression-4.0.1/status.py --check   also exit 1 when the release rule fails
"""

import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).parent
STATUSES = ["open", "confirmed", "fixed", "verified", "deferred", "rejected", "duplicate"]
TYPES = {"functional", "logic", "ux", "visual", "a11y", "perf", "data-loss", "console"}
SEVERITIES = {"S1", "S2", "S3", "S4"}
# Statuses a bug may end in. Everything else still needs work.
FINAL = {"verified", "rejected", "duplicate", "deferred"}
HEADING = re.compile(r"^### (C\d{2}-\d{3}) · (.+?)\s*$")
FIELD = re.compile(r"^- \*\*(Status|Type|Severity|Area|Triage|Fix|Verified):\*\*\s*(.*?)\s*$")


def parse(path: Path) -> list[dict]:
    """Return the bug entries of one file as dicts of field -> value."""
    bugs: list[dict] = []
    current: dict | None = None
    in_fence = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("```"):
            in_fence = not in_fence
        if in_fence:
            continue
        heading = HEADING.match(line)
        if heading:
            current = {"id": heading[1], "title": heading[2], "file": path.name}
            bugs.append(current)
            continue
        field = FIELD.match(line)
        if field and current is not None:
            current[field[1].lower()] = field[2]
    return bugs


def problems(bugs: list[dict]) -> list[str]:
    """Return one message per malformed entry or broken rule."""
    out: list[str] = []
    seen: set[str] = set()
    for bug in bugs:
        bid = bug["id"]
        if bid in seen:
            out.append(f"{bid}: duplicate id")
        seen.add(bid)
        if not bid.startswith(f"C{bug['file'][:2]}-"):
            out.append(f"{bid}: id does not match its file {bug['file']}")
        status = bug.get("status", "").split(" ")[0]
        if status not in STATUSES:
            out.append(f"{bid}: Status must be one of {', '.join(STATUSES)} (got '{bug.get('status', '')}')")
        if bug.get("type") not in TYPES:
            out.append(f"{bid}: Type must be one of {', '.join(sorted(TYPES))} (got '{bug.get('type', '')}')")
        if bug.get("severity") not in SEVERITIES:
            out.append(f"{bid}: Severity must be S1..S4 (got '{bug.get('severity', '')}')")
        if not bug.get("area"):
            out.append(f"{bid}: Area is missing")
        if status == "fixed" and not bug.get("fix"):
            out.append(f"{bid}: fixed but Fix is empty (commit and test, or why none)")
        if status == "verified" and not bug.get("verified"):
            out.append(f"{bid}: verified but Verified is empty")
        if status in {"rejected", "deferred", "duplicate"} and not bug.get("triage"):
            out.append(f"{bid}: {status} but Triage is empty (say why)")
    return out


def release_blockers(bugs: list[dict]) -> list[dict]:
    """Return S1 and S2 bugs that are not in a final status."""
    return [
        b for b in bugs
        if b.get("severity") in {"S1", "S2"} and b.get("status", "").split(" ")[0] not in FINAL
    ]


def render(bugs: list[dict]) -> str:
    """Build the STATUS.md text."""
    files = sorted({b["file"] for b in bugs} | {p.name for p in (HERE / "bugs").glob("*.md")})
    lines = ["# Status", "", "_Generated by `status.py`. Do not edit._", ""]
    lines += ["| Charter | " + " | ".join(STATUSES) + " | total |", "|---|" + "---|" * (len(STATUSES) + 1)]
    totals: Counter = Counter()
    for name in files:
        counts = Counter(b.get("status", "").split(" ")[0] for b in bugs if b["file"] == name)
        totals.update(counts)
        cells = " | ".join(str(counts[s]) if counts[s] else "·" for s in STATUSES)
        lines.append(f"| {name[:-3]} | {cells} | {sum(counts.values())} |")
    cells = " | ".join(str(totals[s]) for s in STATUSES)
    lines += [f"| **all** | {cells} | **{len(bugs)}** |", ""]

    by_type = Counter(b.get("type", "?") for b in bugs)
    by_sev = Counter(b.get("severity", "?") for b in bugs)
    lines += ["By severity: " + ", ".join(f"{k} {by_sev[k]}" for k in sorted(by_sev)) or "none", ""]
    lines += ["By type: " + ", ".join(f"{k} {v}" for k, v in sorted(by_type.items())) or "none", ""]

    todo = [b for b in bugs if b.get("status", "").split(" ")[0] not in FINAL]
    lines += [f"## Not finished ({len(todo)})", ""]
    order = {"S1": 0, "S2": 1, "S3": 2, "S4": 3}
    for b in sorted(todo, key=lambda b: (order.get(b.get("severity", ""), 9), b["id"])):
        lines.append(f"- **{b['id']}** [{b.get('severity', '?')} · {b.get('type', '?')} · {b.get('status', '?')}] {b['title']}")
    if not todo:
        lines.append("Nothing left.")
    return "\n".join(lines) + "\n"


def main() -> int:
    """Rewrite STATUS.md and, with --check, enforce the release rule."""
    bugs = [b for p in sorted((HERE / "bugs").glob("[0-9][0-9]-*.md")) for b in parse(p)]
    (HERE / "STATUS.md").write_text(render(bugs), encoding="utf-8")
    print((HERE / "STATUS.md").read_text(encoding="utf-8"))
    if "--check" not in sys.argv:
        return 0
    bad = problems(bugs)
    blockers = release_blockers(bugs)
    for message in bad:
        print(f"MALFORMED  {message}")
    for b in blockers:
        print(f"BLOCKER    {b['id']} {b.get('severity')} {b.get('status')}: {b['title']}")
    if bad or blockers:
        return 1
    print("OK: release rule met.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
